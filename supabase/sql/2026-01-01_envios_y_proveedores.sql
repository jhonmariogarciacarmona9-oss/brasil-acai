-- 1) Correos multiples y asignacion por tienda en proveedores
alter table public."Tabla De Proveedores"
  add column if not exists emails text[] default '{}'::text[],
  add column if not exists tiendas_asignadas text[] default '{}'::text[];

update public."Tabla De Proveedores"
set emails = case
  when coalesce(email, '') = '' then '{}'::text[]
  else regexp_split_to_array(replace(email, ';', ','), '\\s*,\\s*')
end
where (emails is null or cardinality(emails) = 0);

-- 2) Log de envios automaticos
create table if not exists public.envios_pedidos_log (
  id bigint generated by default as identity primary key,
  proveedor text not null,
  correos text[] not null default '{}'::text[],
  estado text not null check (estado in ('enviado', 'error')),
  detalle text,
  creado_por uuid,
  created_at timestamptz not null default now()
);

create index if not exists idx_envios_pedidos_log_created_at
  on public.envios_pedidos_log(created_at desc);

-- 3) RLS
alter table public.envios_pedidos_log enable row level security;

drop policy if exists envios_log_select on public.envios_pedidos_log;
create policy envios_log_select
on public.envios_pedidos_log
for select
using (
  exists (
    select 1
    from public."Tabla De Perfiles" p
    where p.id = auth.uid()
      and lower(trim(p.rol)) in ('administrador', 'auxiliar_administrativo')
  )
);

drop policy if exists envios_log_insert on public.envios_pedidos_log;
create policy envios_log_insert
on public.envios_pedidos_log
for insert
with check (
  exists (
    select 1
    from public."Tabla De Perfiles" p
    where p.id = auth.uid()
      and lower(trim(p.rol)) in ('administrador', 'auxiliar_administrativo')
  )
);
