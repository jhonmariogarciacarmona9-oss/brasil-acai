-- Alinea los campos con la tabla `proveedores` que usa la aplicación.
alter table public.proveedores
  add column if not exists emails text[] not null default '{}'::text[],
  add column if not exists tiendas_asignadas text[] not null default '{}'::text[];

-- Copia los emails existentes a la lista nueva, aceptando comas o punto y coma.
update public.proveedores
set emails = case
  when coalesce(trim(email), '') = '' then '{}'::text[]
  else regexp_split_to_array(
    regexp_replace(trim(email), '\s*[,;]\s*', ',', 'g'),
    ','
  )
end
where emails is null or cardinality(emails) = 0;

-- Registro de intentos de envío.
create table if not exists public.envios_pedidos_log (
  id bigint generated by default as identity primary key,
  proveedor text not null,
  correos text[] not null default '{}'::text[],
  estado text not null check (estado in ('enviado', 'error')),
  detalle text,
  creado_por uuid,
  created_at timestamptz not null default now()
);

create index if not exists idx_envios_pedidos_log_created_at
  on public.envios_pedidos_log(created_at desc);

alter table public.envios_pedidos_log enable row level security;

-- La app identifica perfiles por nombre_usuario (email); en esta base el campo
-- `id` del perfil está vacío, así que no se puede comparar con auth.uid().
drop policy if exists envios_log_select on public.envios_pedidos_log;
create policy envios_log_select
on public.envios_pedidos_log
for select
using (
  exists (
    select 1
    from public."Tabla De Perfiles" p
    where lower(trim(p.nombre_usuario)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
      and lower(trim(p.rol)) in ('administrador', 'auxiliar_administrativo')
  )
);

drop policy if exists envios_log_insert on public.envios_pedidos_log;
create policy envios_log_insert
on public.envios_pedidos_log
for insert
with check (
  exists (
    select 1
    from public."Tabla De Perfiles" p
    where lower(trim(p.nombre_usuario)) = lower(trim(coalesce(auth.jwt() ->> 'email', '')))
      and lower(trim(p.rol)) in ('administrador', 'auxiliar_administrativo', 'franquiciado')
  )
);
